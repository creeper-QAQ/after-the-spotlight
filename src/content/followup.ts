export function createFollowupCard(question: string) {
  return [
    '被看见之后 · 回访问题卡',
    '',
    '我的问题',
    question.trim(),
    '',
    '以下为待开展的回访提纲，不含采访结果。',
    '开始前征得本人同意，用匿名编号连接同一个人的记录；联系方式另行妥善保管。',
    '',
    ...followupStages.flatMap((stage, index) => [
      `${index + 1}. ${stage.title}`,
      stage.question,
      stage.record,
      '',
    ]),
    '核对时请保留',
    '原始参与人数：____  实际回访人数：____  失访人数：____',
    '持续学习的判定标准：____  信息来源与核对日期：____',
    '没有联系上，不等于没有继续学习；一次体验，不等于已经学会。',
    '',
    '本卡在当前设备生成，可继续编辑；下载操作不会发送输入内容。',
  ].join('\r\n');
}
